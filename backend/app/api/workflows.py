import csv
import io
from datetime import datetime, timezone
from fastapi import APIRouter, Depends, HTTPException, Query, status
from fastapi.responses import PlainTextResponse
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.api.dashboard import compute_kpi_snapshot
from app.api.deps import get_current_user, record_audit
from app.core.database import get_db
from app.models.entities import ActionItem, Department, Finding, ReportRecord, RiskRecord, User
from app.schemas.common import ActionCreateRequest, ActionUpdateRequest, GenerateReportRequest

router = APIRouter(prefix="/api", tags=["Reports Studio & Action Center"])


@router.post("/reports/generate", status_code=status.HTTP_201_CREATED)
async def generate_report(
    payload: GenerateReportRequest,
    user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    snap = await compute_kpi_snapshot(db, user.organization_id)
    findings = (await db.execute(select(Finding).where(Finding.organization_id == user.organization_id))).scalars().all()
    risks = (await db.execute(select(RiskRecord).where(RiskRecord.organization_id == user.organization_id))).scalars().all()

    title = payload.title or f"{payload.report_type.replace('_', ' ').title()} — {payload.period_label}"
    finding_lines = "\n".join(f"- **{f.title}** ({f.severity.upper()}, {int(f.confidence*100)}% conf.): {f.finding}" for f in findings[:4]) or "- No active findings."
    risk_lines = "\n".join(f"- **{r.title}** ({r.severity.upper()}): Est. impact ${r.financial_impact_usd:,.0f}. Mitigation: {r.mitigation_plan}" for r in risks[:4]) or "- No active risks."

    md = (
        f"# {title}\n\n"
        f"**Period:** {payload.period_label} | **Generated by:** {user.full_name}\n\n"
        f"## Verified KPI Snapshot ({snap['latest_period']})\n"
        f"- **Revenue:** ${snap['revenue']:,.0f} ({snap['revenue_change_pct']:+.1f}% QoQ)\n"
        f"- **Operating Expenses:** ${snap['operating_expenses']:,.0f} ({snap['opex_change_pct']:+.1f}% QoQ)\n"
        f"- **Net Profit:** ${snap['net_profit']:,.0f} (Margin: {snap['profit_margin_pct']:.1f}%)\n"
        f"- **Business Health Score:** {snap['business_health_score']}/100\n\n"
        f"## Key AI Findings & Hypotheses\n{finding_lines}\n\n"
        f"## Active Risk Exposure\n{risk_lines}\n"
    )

    report = ReportRecord(
        organization_id=user.organization_id,
        title=title,
        report_type=payload.report_type,
        period_label=payload.period_label,
        departments_included=payload.departments or ["All Departments"],
        summary_markdown=md,
        metrics_snapshot={k: v for k, v in snap.items() if k != "trends"},
        created_by=user.full_name,
    )
    db.add(report)
    await record_audit(db, user.organization_id, user.email, "GENERATE_REPORT", "report", f"Generated '{title}'")
    await db.commit()
    await db.refresh(report)

    return {
        "id": report.id,
        "title": report.title,
        "report_type": report.report_type,
        "period_label": report.period_label,
        "departments_included": report.departments_included,
        "summary_markdown": report.summary_markdown,
        "metrics_snapshot": report.metrics_snapshot,
        "created_by": report.created_by,
        "created_at": report.created_at.isoformat(),
    }


@router.get("/reports")
async def list_reports(user: User = Depends(get_current_user), db: AsyncSession = Depends(get_db)):
    rows = (
        await db.execute(
            select(ReportRecord).where(ReportRecord.organization_id == user.organization_id).order_by(ReportRecord.created_at.desc())
        )
    ).scalars().all()
    return [
        {
            "id": r.id,
            "title": r.title,
            "report_type": r.report_type,
            "period_label": r.period_label,
            "departments_included": r.departments_included,
            "summary_markdown": r.summary_markdown,
            "metrics_snapshot": r.metrics_snapshot,
            "created_by": r.created_by,
            "created_at": r.created_at.isoformat(),
        }
        for r in rows
    ]


@router.get("/reports/{report_id}")
async def get_report(report_id: str, user: User = Depends(get_current_user), db: AsyncSession = Depends(get_db)):
    r = (
        await db.execute(select(ReportRecord).where(ReportRecord.id == report_id, ReportRecord.organization_id == user.organization_id))
    ).scalar_one_or_none()
    if not r:
        raise HTTPException(status_code=404, detail="Report not found.")
    return {
        "id": r.id,
        "title": r.title,
        "report_type": r.report_type,
        "period_label": r.period_label,
        "summary_markdown": r.summary_markdown,
        "metrics_snapshot": r.metrics_snapshot,
        "created_by": r.created_by,
        "created_at": r.created_at.isoformat(),
    }


@router.get("/reports/{report_id}/export")
async def export_report(
    report_id: str,
    fmt: str = Query("csv", pattern="^(csv|md)$"),
    user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    r = (
        await db.execute(select(ReportRecord).where(ReportRecord.id == report_id, ReportRecord.organization_id == user.organization_id))
    ).scalar_one_or_none()
    if not r:
        raise HTTPException(status_code=404, detail="Report not found.")

    if fmt == "md":
        return PlainTextResponse(r.summary_markdown, media_type="text/markdown")

    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["Metric", "Value"])
    for k, v in (r.metrics_snapshot or {}).items():
        writer.writerow([k, v])
    return PlainTextResponse(buf.getvalue(), media_type="text/csv")


@router.get("/actions")
async def list_actions(user: User = Depends(get_current_user), db: AsyncSession = Depends(get_db)):
    rows = (
        await db.execute(
            select(ActionItem).where(ActionItem.organization_id == user.organization_id).order_by(ActionItem.created_at.desc())
        )
    ).scalars().all()
    depts = {
        d.id: d.name
        for d in (await db.execute(select(Department).where(Department.organization_id == user.organization_id))).scalars().all()
    }
    return [
        {
            "id": a.id,
            "title": a.title,
            "description": a.description,
            "department_id": a.department_id,
            "department_name": depts.get(a.department_id, "General"),
            "assigned_to_name": a.assigned_to_name,
            "priority": a.priority,
            "status": a.status,
            "due_date": a.due_date,
            "progress_pct": a.progress_pct,
            "comments": a.comments or [],
            "outcome_note": a.outcome_note,
            "baseline_metric": a.baseline_metric,
            "post_action_metric": a.post_action_metric,
        }
        for a in rows
    ]


@router.post("/actions", status_code=status.HTTP_201_CREATED)
async def create_action(
    payload: ActionCreateRequest,
    user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    item = ActionItem(
        organization_id=user.organization_id,
        department_id=payload.department_id,
        assigned_to_name=payload.assigned_to_name,
        source_finding_id=payload.source_finding_id,
        title=payload.title.strip(),
        description=payload.description.strip(),
        priority=payload.priority,
        due_date=payload.due_date,
        baseline_metric=payload.baseline_metric,
        status="Open",
        progress_pct=0,
    )
    db.add(item)
    await record_audit(db, user.organization_id, user.email, "CREATE_ACTION", "action_item", f"Created action '{item.title}'")
    await db.commit()
    await db.refresh(item)
    return {"id": item.id, "title": item.title, "status": item.status, "priority": item.priority, "due_date": item.due_date}


@router.patch("/actions/{action_id}")
async def update_action(
    action_id: str,
    payload: ActionUpdateRequest,
    user: User = Depends(get_current_user),
    db: AsyncSession = Depends(get_db),
):
    item = (
        await db.execute(select(ActionItem).where(ActionItem.id == action_id, ActionItem.organization_id == user.organization_id))
    ).scalar_one_or_none()
    if not item:
        raise HTTPException(status_code=404, detail="Action item not found.")

    data = payload.model_dump(exclude_unset=True)
    comment_text = data.pop("comment", None)
    if comment_text:
        comments = list(item.comments or [])
        comments.append({"author": user.full_name, "text": comment_text, "at": datetime.now(timezone.utc).isoformat()})
        item.comments = comments

    for field, val in data.items():
        setattr(item, field, val)
    if item.status == "Completed":
        item.progress_pct = 100

    await record_audit(db, user.organization_id, user.email, "UPDATE_ACTION", "action_item", f"Updated '{item.title}' -> {item.status}")
    await db.commit()
    return {
        "id": item.id,
        "title": item.title,
        "status": item.status,
        "progress_pct": item.progress_pct,
        "outcome_note": item.outcome_note,
        "comments": item.comments,
    }
